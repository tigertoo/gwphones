"""WhatsApp calls into the phone system: Meta's SIP gateway hands a call
to the business's WhatsApp number to our Asterisk, which routes it like
any call from a trunk (by the number's inbound route).

Run on the server, as root, from /opt/gwphones/backend:

    venv/bin/python whatsapp.py --phone-id ID --graph-version vNN.0 check
    venv/bin/python whatsapp.py --phone-id ID --graph-version vNN.0 prepare
    venv/bin/python whatsapp.py --phone-id ID --graph-version vNN.0 enable-sip --host pbx.example.com --port 15061
    venv/bin/python whatsapp.py --phone-id ID --graph-version vNN.0 write-conf
    venv/bin/python whatsapp.py --phone-id ID --graph-version vNN.0 disable-sip

From Meta's "Calling with SIP" and "Integration examples" pages:

- Settings go to POST /{phone-number-id}/settings as {"calling": {...}}.
  "prepare" switches calling on with SDES keys (Meta's default is DTLS,
  which our endpoint doesn't use) and G.711 a-law as well as Opus, before
  SIP: once SIP is on, Meta's other calling API calls stop working.
- "enable-sip" points the number at our server: TLS only, the hostname
  on our certificate, and our TLS port. Meta allows one server per number.
- Meta makes one SIP password per number and app, read with
  ?include_sip_credentials=true. "write-conf" puts it in the endpoint's
  outbound auth (Meta challenges our requests with 407, the username
  being the business number in digits) and never prints it.
- Meta's calls come from Meta's addresses, so the endpoint is matched by
  source address only. The X-FB-External-Domain header (Meta's own
  example matches on it) is never trusted: anyone can send it.
- rewrite_contact=no: with it on, our 200 OK loses Meta's Record-Route,
  there's no ACK and the audio stops after about 30 seconds.

The access token is asked for at the prompt each time, never taken from
the command line or a file, and nothing secret is printed or logged.
"""
import argparse
import getpass
import grp
import hashlib
import os
import re
import sys
from typing import List, Optional

import httpx

GRAPH_URL = "https://graph.facebook.com"
TIMEOUT = 15
CONF_PATH = "/etc/asterisk/pjsip_whatsapp.conf"
ENDPOINT = "whatsapp"  # billing.INBOUND_TRUNKS knows it by this name
META_DOMAIN = "wa.meta.vc"
# Meta's addresses, from the ACL in Meta's "Integration examples" page
# (Meta says to keep it up to date: --ranges-file replaces it).
META_RANGES = [
    "31.13.24.0/21", "31.13.64.0/18", "45.64.40.0/22", "57.141.0.0/21", "57.141.8.0/22", "57.141.12.0/23",
    "57.144.0.0/14", "66.220.144.0/20", "69.63.176.0/20", "69.171.224.0/19", "74.119.76.0/22", "102.132.96.0/20",
    "103.4.96.0/22", "129.134.0.0/16", "147.75.208.0/20", "157.240.0.0/16", "163.70.128.0/17", "163.77.128.0/17",
    "173.252.64.0/18", "179.60.192.0/22", "185.60.216.0/22", "185.89.216.0/22", "204.15.20.0/22",
]
CIDR_RE = re.compile(r"^\d{1,3}(\.\d{1,3}){3}/\d{1,2}$|^[0-9a-fA-F:]+/\d{1,3}$")
HOST_RE = re.compile(r"^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}$")
VERSION_RE = re.compile(r"^v\d{1,3}\.\d$")
SECTION_RE = re.compile(r"^[A-Za-z0-9_-]{1,40}$")
CODECS_RE = re.compile(r"^(opus|alaw|ulaw)(,(opus|alaw|ulaw)){0,2}$")


class GraphError(Exception):
    pass


def fingerprint(secret: str) -> str:
    return hashlib.md5(secret.encode()).hexdigest()[:8]


def digits(number: str) -> str:
    """The business number as Meta's SIP username: digits only."""
    d = re.sub(r"\D", "", number or "")
    if not 6 <= len(d) <= 15:
        raise GraphError(f"Meta gave no usable phone number for this phone number id ({len(d)} digits).")
    return d


def read_ranges(path: Optional[str]) -> List[str]:
    if not path:
        return list(META_RANGES)
    with open(path) as f:
        ranges = [ln.split("#", 1)[0].strip() for ln in f]
    ranges = [r for r in ranges if r]
    bad = [r for r in ranges if not CIDR_RE.match(r)]
    if bad or not ranges:
        raise GraphError(f"{path}: not address ranges: {', '.join(bad[:3]) or 'empty'}")
    return ranges


def build_conf(number: str, password: str, host: str, ranges: List[str], transport: str = "transport-tls",
               codecs: str = "opus,alaw") -> str:
    """The [whatsapp] endpoint, for #include pjsip_whatsapp.conf in pjsip.conf."""
    if not HOST_RE.match(host) or not SECTION_RE.match(transport) or not CODECS_RE.match(codecs):
        raise GraphError("Bad hostname, transport name or codecs.")
    if not password or any(c in password for c in "\r\n;"):
        raise GraphError("Meta's SIP password can't be written into the config.")
    number = digits(number)
    out = ["; Generated by gwphones backend/whatsapp.py (write-conf). Holds Meta's SIP password:",
           "; root:asterisk, 0640. Included from pjsip.conf; rewrite it with write-conf.",
           "",
           f"[{ENDPOINT}]",
           "type=endpoint",
           f"transport={transport}",
           "context=from-whatsapp",  # extensions.conf: inbound routes only, never a trunk
           "disallow=all",
           f"allow={codecs}",  # Opus needs Asterisk's Opus translator to reach G.711 phones
           "media_encryption=sdes",
           "direct_media=no",
           "rtp_symmetric=yes",
           "force_rport=yes",
           "rewrite_contact=no",  # keeps Meta's Record-Route (no ACK and silence after ~30 s without)
           "media_use_received_transport=yes",
           "dtmf_mode=rfc4733",
           f"aors={ENDPOINT}",
           f"outbound_auth={ENDPOINT}-auth",
           f"from_user={number}",
           f"from_domain={host}",
           "",
           f"[{ENDPOINT}]",
           "type=aor",
           f"contact=sip:{META_DOMAIN};transport=tls",
           "",
           f"[{ENDPOINT}-auth]",
           "type=auth",
           "auth_type=userpass",
           f"username={number}",
           f"password={password}",
           f"realm={META_DOMAIN}",
           "",
           f"[{ENDPOINT}-identify]",
           "type=identify",
           f"endpoint={ENDPOINT}",
           *[f"match={r}" for r in ranges],
           ""]
    return "\n".join(out)


class Graph:
    def __init__(self, token: str, version: str, phone_id: str, send=None):
        self.token, self.version, self.phone_id = token, version, phone_id
        self._send = send or self._http

    def _http(self, method: str, url: str, headers: dict, params: Optional[dict], body: Optional[dict]):
        with httpx.Client(timeout=TIMEOUT) as c:
            return c.request(method, url, headers=headers, params=params, json=body)

    def call(self, method: str, path: str, params: Optional[dict] = None, body: Optional[dict] = None) -> dict:
        url = f"{GRAPH_URL}/{self.version}/{self.phone_id}{path}"
        try:
            r = self._send(method, url, {"Authorization": f"Bearer {self.token}"}, params, body)
            data = r.json()
        except httpx.HTTPError as e:
            raise GraphError(f"Couldn't reach Meta ({type(e).__name__}).")
        except ValueError:
            raise GraphError(f"Meta's answer wasn't JSON (HTTP {r.status_code}).")
        if not isinstance(data, dict):
            raise GraphError(f"Unexpected answer from Meta (HTTP {r.status_code}).")
        if "error" in data or r.status_code >= 400:
            err = data.get("error") or {}
            msg = str(err.get("message") or f"HTTP {r.status_code}")[:300].replace(self.token, "********")
            raise GraphError(f"Meta said: {msg} (code {err.get('code', '?')})")
        return data

    def number(self) -> str:
        return self.call("GET", "", {"fields": "display_phone_number,verified_name"}).get("display_phone_number", "")

    def settings(self, credentials: bool = False) -> dict:
        return self.call("GET", "/settings", {"include_sip_credentials": "true"} if credentials else None)

    def post_calling(self, calling: dict) -> dict:
        return self.call("POST", "/settings", body={"calling": calling})


def masked(settings: dict) -> dict:
    """Settings without the SIP password, for showing."""
    calling = dict(settings.get("calling") or {})
    sip = dict(calling.get("sip") or {})
    sip["servers"] = [{k: (f"******** ({fingerprint(v)})" if k == "sip_user_password" else v) for k, v in s.items()}
                      for s in sip.get("servers") or []]
    if sip:
        calling["sip"] = sip
    return calling


def show(g: Graph, out=print):
    calling = masked(g.settings())
    sip = calling.get("sip") or {}
    out(f"Number:            {g.number() or '(none)'}")
    out(f"Calling:           {calling.get('status', '(not set)')}")
    out(f"SRTP keys:         {calling.get('srtp_key_exchange_protocol', '(not set: Meta uses DTLS)')}")
    out(f"Extra codecs:      {', '.join((calling.get('audio') or {}).get('additional_codecs') or []) or '(none)'}")
    out(f"SIP:               {sip.get('status', '(not set)')}")
    for s in sip.get("servers") or []:
        out(f"SIP server:        {s.get('hostname')}:{s.get('port')}")


def write_conf(g: Graph, host: str, path: str, ranges: List[str], transport: str, codecs: str = "opus,alaw",
               out=print) -> str:
    settings = g.settings(credentials=True)
    servers = ((settings.get("calling") or {}).get("sip") or {}).get("servers") or []
    if not servers or not servers[0].get("sip_user_password"):
        raise GraphError("Meta has no SIP password for this number yet: run enable-sip first.")
    password = servers[0]["sip_user_password"]
    host = host or servers[0].get("hostname", "")
    text = build_conf(g.number(), password, host, ranges, transport, codecs)
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o640)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o640)
    try:
        os.chown(tmp, 0, grp.getgrnam("asterisk").gr_gid)
    except (KeyError, PermissionError):
        out("Note: couldn't give the file to the asterisk group (run as root on the server).")
    os.replace(tmp, path)
    out(f"Wrote {path} (Meta's SIP password {fingerprint(password)}, {len(ranges)} Meta address ranges).")
    out('Then: asterisk -rx "module reload res_pjsip.so" and asterisk -rx "pjsip show endpoint whatsapp"')
    return path


def main(argv: Optional[List[str]] = None, token_prompt=getpass.getpass, send=None, out=print) -> int:
    p = argparse.ArgumentParser(description="WhatsApp calls into Asterisk through Meta's SIP gateway.")
    p.add_argument("--phone-id", required=True, help="the WhatsApp phone number id (WhatsApp Manager / API setup)")
    p.add_argument("--graph-version", required=True, help="the Graph API version your Meta app uses, e.g. v24.0")
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("check", help="show the number's calling settings (no password)")
    sub.add_parser("prepare", help="calling on, SDES keys, a-law as well as Opus (before enable-sip)")
    e = sub.add_parser("enable-sip", help="send the number's calls to our server")
    e.add_argument("--host", required=True)
    e.add_argument("--port", required=True, type=int)
    sub.add_parser("disable-sip", help="stop sending calls to our server (the server is kept)")
    w = sub.add_parser("write-conf", help="write the Asterisk endpoint with Meta's SIP password")
    w.add_argument("--out", default=CONF_PATH)
    w.add_argument("--host", default="", help="our hostname (default: the one Meta has)")
    w.add_argument("--transport", default="transport-tls")
    w.add_argument("--ranges-file", default="", help="Meta's address ranges, one per line")
    w.add_argument("--codecs", default="opus,alaw", help="alaw alone if Asterisk has no Opus translator")
    a = p.parse_args(argv)

    if not re.fullmatch(r"\d{5,25}", a.phone_id):
        out("--phone-id is the number's id (digits), not the phone number.")
        return 2
    if not VERSION_RE.match(a.graph_version):
        out("--graph-version looks like v24.0.")
        return 2
    try:
        if a.cmd == "enable-sip":
            if not HOST_RE.match(a.host.lower()) or not 1 <= a.port <= 65535:
                raise GraphError("Give our hostname (on our certificate) and our TLS port.")
        ranges = read_ranges(getattr(a, "ranges_file", ""))
        token = (token_prompt("Meta access token (not shown): ") or "").strip()
        if not token:
            out("No token given.")
            return 2
        g = Graph(token, a.graph_version, a.phone_id, send)
        if a.cmd == "check":
            show(g, out)
        elif a.cmd == "prepare":
            g.post_calling({"status": "ENABLED", "srtp_key_exchange_protocol": "SDES",
                            "audio": {"additional_codecs": ["PCMA"]}})
            out("Calling on, SDES keys, a-law as well as Opus. Now:")
            show(g, out)
        elif a.cmd == "enable-sip":
            g.post_calling({"status": "ENABLED", "sip": {"status": "ENABLED",
                                                          "servers": [{"hostname": a.host.lower(), "port": a.port}]}})
            out(f"Calls to this number now go to {a.host.lower()}:{a.port}. Next: write-conf.")
            show(g, out)
        elif a.cmd == "disable-sip":
            g.post_calling({"sip": {"status": "DISABLED"}})
            out("SIP off: WhatsApp calls no longer come to us (the server entry is kept).")
        elif a.cmd == "write-conf":
            write_conf(g, a.host.lower(), a.out, ranges, a.transport, a.codecs, out)
    except GraphError as e:
        out(str(e))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
